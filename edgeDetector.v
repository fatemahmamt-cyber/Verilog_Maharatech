/* ------------------------------------ Module Declarations ------------------------------------- */
module edgeDetector (clk, rstn, syncin, out);
// ----------------------------------- Parameter Declarations ----------------------------------- //
// ------------------------------------- Inputs Declarations ------------------------------------ //
input clk, syncin, rstn;
// ------------------------------------ Outputs Declarations ------------------------------------ //
output out;
// -------------------------------------- Wire Declarations ------------------------------------- //
wire dffo;
// -------------------------------------- Reg Declarations -------------------------------------- //
// ---------------------------------------- Initial setup --------------------------------------- //
// ------------------------------------ Instantiation Modules ----------------------------------- //
dflipflop dff (clk, rstn, syncin, dffo); // delays input
// ------------------------------------- Combinational Logic ------------------------------------ //
assign out = ~syncin & dffo;
// --------------------------------------- Sequential Logic ------------------------------------- //
endmodule
