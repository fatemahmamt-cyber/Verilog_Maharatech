/* ------------------------------------ Module Declarations ------------------------------------- */
module dflipflop (clk, rstn, D, Q);
// ----------------------------------- Parameter Declarations ----------------------------------- //
// ------------------------------------- Inputs Declarations ------------------------------------ //
input reg clk, rstn, D;
// ------------------------------------ Outputs Declarations ------------------------------------ //
output reg Q;
// -------------------------------------- Wire Declarations ------------------------------------- //
// -------------------------------------- Reg Declarations -------------------------------------- //
// ---------------------------------------- Initial setup --------------------------------------- //
// ------------------------------------ Instantiation Modules ----------------------------------- //
// ------------------------------------- Combinational Logic ------------------------------------ //
// --------------------------------------- Sequential Logic ------------------------------------- //
always@ (posedge clk or negedge rstn)
begin
    if(~rstn) Q <= 0;
    else Q <= D;
end
endmodule
